const char *A3_SHADER_GRID_VS =
    "layout(location=0) in vec3 a_position;\n"
    "uniform mat4 u_view_proj;\n"
    "uniform vec3 u_camera_pos;\n"
    "out vec3 v_world;\n"
    "void main() {\n"
    "    vec3 p = a_position * 500.0 + vec3(u_camera_pos.x, 0.0, u_camera_pos.z);\n"
    "    v_world = p;\n"
    "    gl_Position = u_view_proj * vec4(p, 1.0);\n"
    "}\n";

const char *A3_SHADER_GRID_FS =
    "in vec3 v_world;\n"
    "out vec4 o_color;\n"
    "uniform vec3 u_camera_pos;\n"
    "float grid(vec2 p, float scale) {\n"
    "    vec2 c = p / scale; vec2 d = fwidth(c);\n"
    "    vec2 g = abs(fract(c - 0.5) - 0.5) / d;\n"
    "    return 1.0 - min(min(g.x, g.y), 1.0);\n"
    "}\n"
    "void main() {\n"
    "    float dist = length(v_world.xz - u_camera_pos.xz);\n"
    "    float fade = 1.0 - smoothstep(30.0, 180.0, dist);\n"
    "    float g1 = grid(v_world.xz, 1.0) * 0.35, g10 = grid(v_world.xz, 10.0) * 0.6;\n"
    "    float a = max(g1, g10) * fade;\n"
    "    vec3 col = vec3(0.55);\n"
    "    if (abs(v_world.z) < fwidth(v_world.z) * 1.5) { col = vec3(0.9, 0.25, 0.25); a = fade; }\n"
    "    if (abs(v_world.x) < fwidth(v_world.x) * 1.5) { col = vec3(0.25, 0.45, 0.95); a = fade; }\n"
    "    if (a < 0.01) discard;\n"
    "    o_color = vec4(col, a);\n"
    "}\n";

/* Camera-facing particles: per-instance position/size (loc 4), color (loc 8). */
const char *A3_SHADER_PARTICLE_VS =
    "layout(location=0) in vec3 a_position;\n"
    "layout(location=2) in vec2 a_uv;\n"
    "layout(location=4) in vec4 i_pos_size;\n"
    "layout(location=8) in vec4 i_color;\n"
    "uniform mat4 u_view_proj;\n"
    "uniform vec3 u_cam_right;\n"
    "uniform vec3 u_cam_up;\n"
    "out vec2 v_uv;\n"
    "out vec4 v_color;\n"
    "void main() {\n"
    "    vec3 p = i_pos_size.xyz + (u_cam_right * a_position.x + u_cam_up * a_position.y) * i_pos_size.w;\n"
    "    v_uv = a_uv; v_color = i_color;\n"
    "    gl_Position = u_view_proj * vec4(p, 1.0);\n"
    "}\n";

const char *A3_SHADER_PARTICLE_FS =
    "in vec2 v_uv;\n"
    "in vec4 v_color;\n"
    "out vec4 o_color;\n"
    "uniform sampler2D u_tex;\n"
    "uniform int u_has_texture;\n"
    "void main() {\n"
    "    vec2 d = v_uv * 2.0 - 1.0;\n"
    "    float soft = clamp(1.0 - dot(d, d), 0.0, 1.0);\n"
    "    vec4 c = v_color;\n"
    "    if (u_has_texture != 0) c *= texture(u_tex, v_uv); else c.a *= soft * soft;\n"
    "    if (c.a < 0.003) discard;\n"
    "    o_color = c;\n"
    "}\n";
