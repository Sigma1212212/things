    "layout(location=0) in vec3 a_position;\n"
    "layout(location=1) in vec3 a_normal;\n"
    "layout(location=2) in vec2 a_uv;\n"
    "layout(location=4) in vec4 i_m0;\n"
    "layout(location=5) in vec4 i_m1;\n"
    "layout(location=6) in vec4 i_m2;\n"
    "layout(location=7) in vec4 i_m3;\n"
    "layout(location=8) in vec4 i_color;\n"
    "layout(location=9) in vec4 i_params;\n"
    "layout(location=10) in vec4 i_lights0;\n"
    "layout(location=11) in vec4 i_lights1;\n"
    "uniform mat4 u_view_proj;\n"
    "uniform mat4 u_light_view_proj;\n"
    "flat out vec4 v_lights0;\n"
    "flat out vec4 v_lights1;\n"
    "out vec3 v_world_pos;\n"
    "out vec3 v_normal;\n"
    "out vec2 v_uv;\n"
    "out vec4 v_color;\n"
    "out vec4 v_params;\n"
    "out vec4 v_shadow_pos;\n"
    "out vec3 v_local_pos;\n"
    "void main() {\n"
    "    mat4 model = mat4(i_m0, i_m1, i_m2, i_m3);\n"
    "    vec4 wp = model * vec4(a_position, 1.0);\n"
    "    mat3 m = mat3(model);\n"
    "    mat3 normal_matrix = mat3(cross(m[1], m[2]), cross(m[2], m[0]), cross(m[0], m[1]));\n"
    "    v_world_pos = wp.xyz;\n"
    "    v_normal = normalize(normal_matrix * a_normal);\n"
    "    v_uv = a_uv;\n"
    "    v_color = i_color;\n"
    "    v_params = i_params;\n"
    "    v_shadow_pos = u_light_view_proj * wp;\n"
    "    v_local_pos = a_position;\n"
    "    v_lights0 = i_lights0;\n"
    "    v_lights1 = i_lights1;\n"
    "    gl_Position = u_view_proj * wp;\n"
    "}\n";

const char *A3_SHADER_LIT_FS_HEAD =
    "in vec3 v_world_pos;\n"
    "in vec3 v_normal;\n"
    "in vec2 v_uv;\n"
    "in vec4 v_color;\n"
    "in vec4 v_params;\n"
    "in vec4 v_shadow_pos;\n"
    "in vec3 v_local_pos;\n"
    "flat in vec4 v_lights0;\n"
    "flat in vec4 v_lights1;\n"
    "layout(location=0) out vec4 o_color;\n"
    "layout(location=1) out vec4 o_normal;\n"   /* world normal * 0.5 + 0.5, roughness (for SSAO / SSR) */
    "uniform sampler2D u_albedo_tex;\n"
    "uniform int u_has_texture;\n"
    "uniform sampler2DShadow u_shadow_map;\n"
    "uniform int u_shadows_enabled;\n"
    "uniform vec2 u_shadow_texel;\n"
    "uniform mat4 u_cascade_vp0;\n"
    "uniform mat4 u_cascade_vp1;\n"
    "uniform mat4 u_cascade_vp2;\n"
    "uniform vec3 u_cascade_split;\n"   /* far distance of each cascade (m) */
    "uniform vec3 u_cascade_texel;\n"   /* world size of one shadow texel per cascade */
    "uniform vec3 u_cascade_depth;\n"   /* 1 / depth range per cascade */
    "uniform vec3 u_camera_pos;\n"
    "uniform float u_time;\n"
    "uniform vec3 u_sun_dir;\n"          /* direction the light travels */
    "uniform vec3 u_sun_color;\n"
    "uniform vec3 u_sky_color;\n"
    "uniform vec3 u_sky_horizon;\n"
    "uniform vec3 u_ground_color;\n"
    "uniform float u_ambient;\n"
    "uniform vec3 u_fog_color;\n"
    "uniform float u_fog_density;\n"
    /* local lights: 256 per row, 3 texels each (position + range, color + type, spot direction + cos) */
    "uniform sampler2D u_light_tex;\n"
    "uniform int u_fog_in_post;\n"
    "uniform vec4 u_material[4];\n"                  /* custom material parameters (Shader Maker) */
    "uniform sampler2D u_tex1;\n"
    "uniform sampler2D u_tex2;\n"
    "const float PI = 3.14159265;\n"
    "struct A3Surface {\n"
    "    vec3 albedo; float alpha; vec3 normal; float metallic; float roughness; vec3 emissive; float occlusion;\n"
    "    vec2 uv; vec4 color; vec3 world_pos; vec3 local_pos; vec3 view_dir; float time;\n"
    "};\n"
    "vec3 a3_hash3(vec3 p) { p = fract(p * vec3(443.897, 441.423, 437.195)); p += dot(p, p.yxz + 19.19); return fract((p.xxy + p.yxx) * p.zyx); }\n"
    "float a3_noise(vec3 p) {\n"
    "    vec3 i = floor(p); vec3 f = fract(p); f = f * f * (3.0 - 2.0 * f);\n"
    "    float n000 = a3_hash3(i).x, n100 = a3_hash3(i + vec3(1,0,0)).x, n010 = a3_hash3(i + vec3(0,1,0)).x, n110 = a3_hash3(i + vec3(1,1,0)).x;\n"
    "    float n001 = a3_hash3(i + vec3(0,0,1)).x, n101 = a3_hash3(i + vec3(1,0,1)).x, n011 = a3_hash3(i + vec3(0,1,1)).x, n111 = a3_hash3(i + vec3(1,1,1)).x;\n"
    "    return mix(mix(mix(n000, n100, f.x), mix(n010, n110, f.x), f.y), mix(mix(n001, n101, f.x), mix(n011, n111, f.x), f.y), f.z);\n"
    "}\n"
    "float a3_fbm(vec3 p) { float s = 0.0, a = 0.5; for (int i = 0; i < 5; ++i) { s += a * a3_noise(p); p *= 2.02; a *= 0.5; } return s; }\n"
    /* bump mapping without tangents: h = surface height in meters at p (any
       procedural pattern); returns the perturbed normal. Fades with distance
       so fine detail does not sparkle far away. */
    "vec3 a3_bump(vec3 n, vec3 p, float h) {\n"
    "    vec3 dpx = dFdx(p), dpy = dFdy(p);\n"
    "    float dhx = dFdx(h), dhy = dFdy(h);\n"
    "    vec3 r1 = cross(dpy, n), r2 = cross(n, dpx);\n"
    "    float det = dot(dpx, r1);\n"
    "    if (abs(det) < 1e-12) return n;\n"
    "    vec3 grad = sign(det) * (dhx * r1 + dhy * r2);\n"
    "    float fade = 1.0 / (1.0 + length(u_camera_pos - p) * 0.04);\n"
    "    return normalize(abs(det) * n - grad * fade);\n"
    "}\n"
    "/* ---- surface function (default or generated by the Shader Maker) ---- */\n";

const char *A3_SHADER_DEFAULT_SURFACE =
    "void a3_surface(inout A3Surface s) {\n"
    "    vec3 base = s.color.rgb;\n"
    "    if (u_has_texture != 0) { vec4 t = texture(u_albedo_tex, s.uv); base *= t.rgb; s.alpha *= t.a; }\n"
    "    s.albedo = base;\n"
    "}\n";

const char *A3_SHADER_LIT_FS_TAIL =
    "/* ---- lighting ---- */\n"
    "float a3_distribution_ggx(float ndh, float r) { float a = r * r; float a2 = a * a; float d = ndh * ndh * (a2 - 1.0) + 1.0; return a2 / (PI * d * d + 1e-6); }\n"
    "float a3_geometry(float ndv, float ndl, float r) { float k = (r + 1.0); k = k * k / 8.0; return (ndv / (ndv * (1.0 - k) + k)) * (ndl / (ndl * (1.0 - k) + k)); }\n"
    "vec3 a3_fresnel(float c, vec3 f0) { return f0 + (1.0 - f0) * pow(clamp(1.0 - c, 0.0, 1.0), 5.0); }\n"
    "vec3 a3_brdf(A3Surface s, vec3 l, vec3 radiance) {\n"
    "    vec3 n = s.normal, v = s.view_dir, h = normalize(l + v);\n"
    "    float ndl = max(dot(n, l), 0.0); if (ndl <= 0.0) return vec3(0.0);\n"
    "    float ndv = max(dot(n, v), 1e-4), ndh = max(dot(n, h), 0.0);\n"
    "    float r = clamp(s.roughness, 0.04, 1.0);\n"
    "    vec3 f0 = mix(vec3(0.04), s.albedo, s.metallic);\n"
    "    vec3 f = a3_fresnel(max(dot(h, v), 0.0), f0);\n"
    "    vec3 spec = min(a3_distribution_ggx(ndh, r) * a3_geometry(ndv, ndl, r) * f / (4.0 * ndv * ndl + 1e-4), vec3(40.0));\n"
    "    vec3 kd = (1.0 - f) * (1.0 - s.metallic);\n"
    "    return (kd * s.albedo / PI + spec) * radiance * ndl;\n"
    "}\n"
    /* cascaded shadow maps: 3 tiles of a 2x2 atlas, picked by distance, normal offset + slope bias in meters */
    "float a3_shadow(vec3 n) {\n"
    "    if (u_shadows_enabled == 0 || v_params.w < 0.5) return 1.0;\n"
    "    float dist = length(u_camera_pos - v_world_pos);\n"
    "    if (dist > u_cascade_split.z) return 1.0;\n"
    "    int c = dist < u_cascade_split.x ? 0 : (dist < u_cascade_split.y ? 1 : 2);\n"
    "    mat4 m = c == 0 ? u_cascade_vp0 : (c == 1 ? u_cascade_vp1 : u_cascade_vp2);\n"
    "    float texel = c == 0 ? u_cascade_texel.x : (c == 1 ? u_cascade_texel.y : u_cascade_texel.z);\n"
    "    float dscale = c == 0 ? u_cascade_depth.x : (c == 1 ? u_cascade_depth.y : u_cascade_depth.z);\n"
    "    float ndl = clamp(dot(n, -u_sun_dir), 0.0, 1.0);\n"
    "    vec3 wp = v_world_pos + n * texel * (1.0 + 1.5 * (1.0 - ndl));\n"
    "    vec4 sp = m * vec4(wp, 1.0);\n"
    "    vec3 p = sp.xyz / sp.w * 0.5 + 0.5;\n"
    "    if (p.z > 1.0 || p.x < 0.0 || p.x > 1.0 || p.y < 0.0 || p.y > 1.0) return 1.0;\n"
    "    vec2 off = vec2(c == 1 ? 0.5 : 0.0, c == 2 ? 0.5 : 0.0);\n"
    "    vec2 lo = off + u_shadow_texel * 1.5, hi = off + vec2(0.5) - u_shadow_texel * 1.5;\n"
    "    vec2 uv = p.xy * 0.5 + off;\n"
    "    float bias = texel * (0.6 + 1.5 * (1.0 - ndl)) * dscale;\n"
    "    float sum = 0.0;\n"
    "    for (int y = -1; y <= 1; ++y) for (int x = -1; x <= 1; ++x)\n"
    "        sum += texture(u_shadow_map, vec3(clamp(uv + vec2(x, y) * u_shadow_texel, lo, hi), p.z - bias));\n"
    "    return mix(sum / 9.0, 1.0, smoothstep(u_cascade_split.z * 0.85, u_cascade_split.z, dist));\n"
    "}\n"
    "void main() {\n"
    "    A3Surface s;\n"
    "    s.color = v_color; s.uv = v_uv; s.world_pos = v_world_pos; s.local_pos = v_local_pos; s.time = u_time;\n"
    "    s.view_dir = normalize(u_camera_pos - v_world_pos);\n"
    "    s.normal = normalize(gl_FrontFacing ? v_normal : -v_normal);\n"
    "    s.albedo = v_color.rgb; s.alpha = v_color.a; s.metallic = v_params.x; s.roughness = v_params.y;\n"
    "    s.emissive = vec3(0.0); s.occlusion = 1.0;\n"
    "    a3_surface(s);\n"
    "    s.normal = normalize(s.normal);\n"
    "    vec3 color = vec3(0.0);\n"
    "    /* sun */\n"
    "    color += a3_brdf(s, -u_sun_dir, u_sun_color) * a3_shadow(s.normal);\n"
    "    /* local lights */\n"
    "    for (int k = 0; k < 8; ++k) {\n"
    "        float fi = k < 4 ? v_lights0[k] : v_lights1[k - 4];\n"
    "        if (fi < 0.0) break;\n"
    "        int li = int(fi + 0.5);\n"
    "        ivec2 base = ivec2((li % 256) * 3, li / 256);\n"
    "        vec4 lp = texelFetch(u_light_tex, base, 0);\n"
    "        vec4 lc = texelFetch(u_light_tex, base + ivec2(1, 0), 0);\n"
    "        vec3 lv = lp.xyz - s.world_pos; float d = length(lv); vec3 l = lv / max(d, 1e-4);\n"
    "        float range = lp.w;\n"
    "        float att = clamp(1.0 - pow(d / range, 4.0), 0.0, 1.0); att = att * att / (d * d + 1.0);\n"
    "        if (lc.w > 1.5) {\n"
    "            vec4 ld = texelFetch(u_light_tex, base + ivec2(2, 0), 0);\n"
    "            float c = dot(-l, ld.xyz); float outer = ld.w;\n"
    "            att *= smoothstep(outer, mix(outer, 1.0, 0.25), c);\n"
    "        }\n"
    "        color += a3_brdf(s, l, lc.rgb * att);\n"
    "    }\n"
    "    /* hemispheric ambient */\n"
    "    float up = s.normal.y * 0.5 + 0.5;\n"
    "    vec3 amb = mix(u_ground_color, mix(u_sky_horizon, u_sky_color, 0.4), up) * u_ambient;\n"
    "    vec3 f0a = mix(vec3(0.04), s.albedo, s.metallic);\n"
    "    float ndv_a = max(dot(s.normal, s.view_dir), 1e-4);\n"
    "    vec3 fa = f0a + (max(vec3(1.0 - s.roughness), f0a) - f0a) * pow(clamp(1.0 - ndv_a, 0.0, 1.0), 5.0);\n"
    "    vec3 refl = reflect(-s.view_dir, s.normal);\n"
    /* environment reflection: the sky gradient for smooth surfaces, blurred to the ambient term when rough */
    "    vec3 sky_refl = refl.y >= 0.0 ? mix(u_sky_horizon, u_sky_color, pow(clamp(refl.y, 0.0, 1.0), 0.45)) : mix(u_sky_horizon, u_ground_color, clamp(-refl.y * 4.0, 0.0, 1.0));\n"
    "    vec3 env = mix(sky_refl, mix(u_ground_color, u_sky_color, smoothstep(-0.2, 0.4, refl.y)) * u_ambient * 2.0, clamp(s.roughness * 1.6, 0.0, 1.0));\n"
    "    color += (amb * s.albedo * (1.0 - fa) * (1.0 - s.metallic) + env * fa * (1.0 - s.roughness * 0.6)) * s.occlusion;\n"
    "    color += s.emissive + s.albedo * v_params.z;\n"
    "    /* fog (done in the post pass for opaque surfaces) */\n"
    "    if (u_fog_in_post == 0 || s.alpha < 0.999) {\n"
    "        float dist = length(u_camera_pos - s.world_pos);\n"
    "        float fog = 1.0 - exp(-u_fog_density * dist);\n"
    "        color = mix(color, u_fog_color, clamp(fog, 0.0, 1.0));\n"
    "    }\n"
    "    if (any(isnan(color))) color = vec3(0.0);\n"
    "    o_color = vec4(max(color, vec3(0.0)), s.alpha);\n"
    "    o_normal = vec4(s.normal * 0.5 + 0.5, clamp(s.roughness, 0.0, 1.0));\n"
    "}\n";

int a3_shader_surface_line_offset(void) {
    int lines = 0;
    for (const char *p = A3_SHADER_LIT_FS_HEAD; *p; ++p) if (*p == '\n') ++lines;
    return lines;
}

